-- Run in the database configured in every n8n Postgres node.
-- For a new installation only: IF NOT EXISTS does not migrate an existing table.
CREATE TABLE IF NOT EXISTS public.calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id TEXT NOT NULL UNIQUE,
    transcript TEXT NOT NULL,
    analysis JSONB,
    status TEXT NOT NULL CHECK (status IN ('analyzed', 'error')),
    score JSONB,
    score_model TEXT,
    scored_at TIMESTAMPTZ
);

COMMENT ON COLUMN public.calls.call_id IS
    'WAV filename without extension; conflict key for the workflow upsert.';
COMMENT ON COLUMN public.calls.analysis IS
    'Structured sales analysis from the main model.';
COMMENT ON COLUMN public.calls.status IS
    'analyzed or error; scoring does not change analyzed to another status.';
COMMENT ON COLUMN public.calls.score IS
    'Five nullable 0-2 scores, corresponding reasons, and up to three recommendations.';
COMMENT ON COLUMN public.calls.score_model IS
    'Model identifier stored by the Save Score node.';
COMMENT ON COLUMN public.calls.scored_at IS
    'Database timestamp assigned when the score is saved.';
